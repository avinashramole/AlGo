import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

test("Market tape shows Option Chain lots and hides the extra chip row", () => {
  const tape = fs.readFileSync(path.join(root, "src/components/dashboard/TickerStrip.tsx"), "utf8");
  const options = fs.readFileSync(path.join(root, "src/pages/Options.tsx"), "utf8");
  const markets = fs.readFileSync(path.join(root, "src/lib/markets.ts"), "utf8");

  assert.match(tape, /MEMBER_TAPE_UNDERLYINGS\.map/);
  assert.match(tape, /item\.id !== "MIDCPNIFTY"/);
  assert.match(tape, /tapeScriptTitle/);
  assert.doesNotMatch(tape, /tapeLotLine/);
  assert.doesNotMatch(tape, />Lot</);
  assert.match(tape, /TapeTodayChange/);
  assert.doesNotMatch(tape, /item\.future \|\| item\.price/);
  assert.doesNotMatch(tape, /quote\?\.future \|\| quote\?\.price/);
  const css = fs.readFileSync(path.join(root, "src/index.css"), "utf8");
  assert.match(css, /@media \(max-width: 767px\) \{[\s\S]*\.tape-strip \{[\s\S]*grid-template-columns: repeat\(2/);
  assert.match(css, /@media \(min-width: 768px\) and \(max-width: 1023px\) \{[\s\S]*\.tape-strip \{[\s\S]*grid-template-columns: repeat\(3/);
  assert.match(css, /html\.t2s-hybrid \.tape-strip \{[\s\S]*grid-template-columns: repeat\(2/);
  const deskTape = fs.readFileSync(path.join(root, "src/components/dashboard/DeskTape.tsx"), "utf8");
  assert.match(deskTape, /data-market-tape/);
  const format = fs.readFileSync(path.join(root, "src/lib/format.ts"), "utf8");
  assert.match(format, /export function tapeScriptTitle/);
  assert.doesNotMatch(format, /Lot · \$\{rows/);
  const memberTape = fs.readFileSync(path.join(root, "src/components/dashboard/MemberIndexBoard.tsx"), "utf8");
  const today = fs.readFileSync(path.join(root, "src/components/dashboard/TapeTodayChange.tsx"), "utf8");
  assert.match(memberTape, /TapeTodayChange/);
  assert.match(memberTape, /tapeScriptTitle/);
  assert.doesNotMatch(memberTape, /tapeLotLine/);
  assert.match(memberTape, /tapeSessionLabel/);
  assert.doesNotMatch(memberTape, />Lot</);
  assert.match(today, /data-today-change="true"/);
  assert.match(today, />Today</);
  assert.match(today, /quoteTone/);
  assert.match(today, /bg-emerald-50/);
  assert.match(today, /bg-rose-50/);
  assert.match(markets, /\{ id: "NIFTY", label: "NIFTY", lot: 65 \}/);
  assert.match(markets, /\{ id: "BANKNIFTY", label: "BANKNIFTY", lot: 30 \}/);
  assert.match(markets, /\{ id: "FINNIFTY", label: "FINNIFTY", lot: 60 \}/);
  assert.doesNotMatch(markets, /\{ id: "MIDCPNIFTY"/);
  assert.match(markets, /MEMBER_TAPE_UNDERLYINGS = OPTION_UNDERLYINGS.filter\(\(row\) => row.id !== "MIDCPNIFTY"\)/);
  const market = fs.readFileSync(path.join(root, "server/market.js"), "utf8");
  assert.match(market, /function tapeUnderlyings/);
  assert.match(market, /row\.id !== "MIDCPNIFTY"/);
  assert.match(markets, /\{ id: "SENSEX", label: "SENSEX", lot: 20 \}/);
  assert.match(markets, /\{ id: "CRUDEOIL", label: "CRUDE OIL", lot: 100 \}/);
  assert.match(markets, /\{ id: "NATURALGAS", label: "NATURAL GAS", lot: 1250 \}/);
  assert.match(markets, /\{ id: "COPPER", label: "COPPER", lot: 2500 \}/);
  assert.equal(options.includes("{item.label} · {item.lot}"), false);
  assert.match(options, /TickerStrip selectedId/);
  assert.match(options, /data-option-chain-map="true"/);
  assert.match(options, /Map clients/);
  assert.match(options, /saveOptionChainMap/);
  assert.match(options, /Map clients to option chain/);
  assert.match(options, /Master \+ selected clients/);
  assert.doesNotMatch(options, /data-option-order-type=/);
  assert.doesNotMatch(options, /data-option-limit-price=/);
  assert.doesNotMatch(options, /setOrderType/);
  assert.doesNotMatch(options, /limitPrice/);
  assert.match(options, /<OptionIdsTape lots=\{lots\} \/>/);
  assert.match(options, /BUY\/SELL on a strike opens Market or Limit at that strike/);
  assert.match(options, /ATM ±5/);
  assert.doesNotMatch(options, /ATM ±10/);
  assert.match(options, /capStrikeWindow/);
  const optionTape = fs.readFileSync(path.join(root, "src/components/dashboard/OptionIdsTape.tsx"), "utf8");
  assert.match(optionTape, /function optionTickPrice/);
  assert.match(optionTape, /Math\.round\(n \* 20\) \/ 20/);
  assert.match(optionTape, /data-option-order-ticket="true"/);
  assert.match(optionTape, /data-option-order-type=\{type\}/);
  assert.match(optionTape, /data-option-limit-price="true"/);
  assert.match(optionTape, /data-option-order-place="true"/);
  assert.match(optionTape, /setTicketType\("LIMIT"\)/);
  assert.match(optionTape, /type: useLimit \? "LIMIT" : "MARKET"/);
  assert.match(optionTape, /Enter a Limit price/);
  assert.match(optionTape, /LIMIT @ \$\{limit\}/);
  assert.match(optionTape, /Place \$\{ticket\.side\}/);
  assert.doesNotMatch(optionTape, /type: "MARKET"/);
  assert.match(optionTape, /ATM ±5/);
  assert.doesNotMatch(optionTape, /ATM ±10/);
  assert.match(optionTape, /capStrikeWindow/);
  const mobile = fs.readFileSync(path.join(root, "mobile/src/screens/OptionsScreen.tsx"), "utf8");
  assert.match(mobile, /type: useLimit \? "LIMIT" : "MARKET"/);
  assert.match(mobile, /Limit price/);
  assert.match(mobile, /setTicketType\("LIMIT"\)/);
  assert.match(mobile, /Place \{ticket\.side\}/);
  assert.match(mobile, /Tap BUY or SELL on a strike/);
  assert.match(mobile, /ATM ±5/);
  assert.doesNotMatch(mobile, /ATM ±10/);
  assert.match(mobile, /capStrikeWindow/);
  const client = fs.readFileSync(path.join(root, "src/api/client.ts"), "utf8");
  assert.match(client, /export function saveOptionChainMap/);
  assert.match(client, /optionChainMap\?:/);
  const index = fs.readFileSync(path.join(root, "server/index.js"), "utf8");
  assert.match(index, /app.post\("\/api\/option-chain-map"/);
});
