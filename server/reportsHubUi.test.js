const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

test("Reports hub is Position & Orders with Position, Orders, then Reports tabs", () => {
  const hub = fs.readFileSync(path.join(root, "src/pages/ReportsHub.tsx"), "utf8");
  const tabsFile = fs.readFileSync(path.join(root, "src/lib/bookTabs.ts"), "utf8");
  const app = fs.readFileSync(path.join(root, "src/App.tsx"), "utf8");
  const side = fs.readFileSync(path.join(root, "src/components/layout/Sidebar.tsx"), "utf8");
  assert.match(hub, /Position & Orders/);
  assert.match(hub, /data-reports-tabs="position-order-reports"/);
  assert.match(tabsFile, /if \(value === "orders"\) return "orders";/);
  assert.match(tabsFile, /if \(value === "reports"\) return "reports";/);
  assert.match(tabsFile, /if \(value === "paper" && allowPaper\) return "paper";/);
  assert.match(tabsFile, /return "positions";/);
  assert.match(app, /Navigate to="\/reports\?tab=orders"/);
  assert.match(app, /Navigate to="\/reports\?tab=positions"/);
  assert.match(side, /label: "Position & Orders", icon: FileText, admin: true/);
  assert.match(side, /to: "\/positions", label: "Position"/);
  assert.match(side, /to: "\/orders", label: "Orders"/);
  const tabs = hub.split("desk-tabs")[1] || "";
  const position = tabs.indexOf("Position");
  const orders = tabs.indexOf("Orders");
  const reports = tabs.lastIndexOf("Reports");
  assert.ok(position >= 0 && orders > position && reports > orders);
  const reportsPage = fs.readFileSync(path.join(root, "src/pages/Reports.tsx"), "utf8");
  const ordersPage = fs.readFileSync(path.join(root, "src/pages/Orders.tsx"), "utf8");
  const book = fs.readFileSync(path.join(root, "src/pages/MemberBook.tsx"), "utf8");
  assert.match(reportsPage, /data-profit-people="true"/);
  assert.match(reportsPage, />Name</);
  assert.match(reportsPage, />Email</);
  assert.match(reportsPage, />Mobile</);
  assert.match(reportsPage, />Broker</);
  assert.match(reportsPage, />Position</);
  assert.match(reportsPage, /data-daily-pnl="true"/);
  assert.match(reportsPage, /Last 5 trading days/);
  assert.match(reportsPage, /liveDailyPnl/);
  assert.match(reportsPage, />Why</);
  assert.match(reportsPage, /whyColClass/);
  assert.match(book, /Last 5 trading days/);
  assert.match(book, /liveDailyPnl/);
  const formatLib = fs.readFileSync(path.join(root, "src/lib/format.ts"), "utf8");
  assert.match(formatLib, /whyColClass = "w-px whitespace-nowrap"/);
  const whyLib = fs.readFileSync(path.join(root, "src/lib/exitReason.ts"), "utf8");
  assert.match(whyLib, /export function closeWhyFromPrices/);
  assert.match(whyLib, /export function orderWhyForBook/);
  const dailyPnl = fs.readFileSync(path.join(root, "src/lib/dailyPnl.ts"), "utf8");
  assert.match(dailyPnl, /lastTradingDayKeys/);
  assert.match(dailyPnl, /2026-08-1\[2-8\]/);
  assert.doesNotMatch(reportsPage, /\{ \(report\.daily \|\| \[\]\)\.map/);
  assert.doesNotMatch(book, /\{ \(report\?\.daily \|\| \[\]\)\.map/);
  assert.match(ordersPage, />Why</);
  assert.match(ordersPage, /whyColClass/);
  assert.match(ordersPage, /data-order-why="true"/);
  assert.match(ordersPage, /orderWhyForBook\(row, orders\) \|\| "—"/);
  assert.doesNotMatch(ordersPage, /Reason: \{displayOrderReason/);
  assert.match(ordersPage, /book === "paper"/);
  assert.match(ordersPage, /isLiveBrokerTrade/);
  assert.match(book, />Why</);
  assert.match(book, /w-max shrink-0 whitespace-nowrap/);
  assert.match(book, /orderWhyForBook\(row, book\)/);
  assert.doesNotMatch(book, /After exit/);
  assert.match(book, /data-book-meta="strategy-exit"/);
  assert.doesNotMatch(book, /ProfitOwnerCard/);
  assert.doesNotMatch(book, /data-profit-owner/);
  assert.match(book, /data-paper-tab="true"/);
  assert.match(book, /data-member-book="paper"/);
  assert.match(hub, /data-paper-tab="true"/);
  assert.match(hub, /book="live"/);
  assert.match(hub, /PaperTrading/);
  const paperPage = fs.readFileSync(path.join(root, "src/pages/PaperTrading.tsx"), "utf8");
  assert.match(paperPage, /data-paper-book="true"/);
  assert.match(paperPage, /book="paper"/);
  const liveBook = fs.readFileSync(path.join(root, "src/components/desk/MemberLiveBook.tsx"), "utf8");
  assert.match(liveBook, />Why</);
  assert.match(liveBook, /whyColClass/);
  assert.match(liveBook, /orderWhyForBook\(row,/);
  assert.doesNotMatch(liveBook, /After exit/);
  assert.match(liveBook, />Strategy</);
  const userDetail = fs.readFileSync(path.join(root, "src/components/users/UserDetailModal.tsx"), "utf8");
  assert.match(userDetail, />Strategy</);
  assert.match(userDetail, />Why</);
  assert.match(userDetail, /whyColClass/);
  assert.match(userDetail, /displayOrderReason\(item\) \|\| "—"/);
  assert.match(liveBook, /8:00 AM IST/);
  assert.match(ordersPage, /8:00 AM IST/);
  assert.match(reportsPage, /8:00 AM IST/);
});

