import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

test("Reports hub is Position & Orders with Position, Orders, then Reports tabs", () => {
  const hub = fs.readFileSync(path.join(root, "src/pages/ReportsHub.tsx"), "utf8");
  const tabsFile = fs.readFileSync(path.join(root, "src/lib/bookTabs.ts"), "utf8");
  const app = fs.readFileSync(path.join(root, "src/App.tsx"), "utf8");
  const side = fs.readFileSync(path.join(root, "src/components/layout/Sidebar.tsx"), "utf8");
  assert.match(hub, /Position & Orders/);
  assert.match(hub, /data-reports-tabs="position-order-reports"/);
  assert.match(tabsFile, /if \(value === "orders"\) return "orders";/);
  assert.match(tabsFile, /if \(value === "reports"\) return "reports";/);
  assert.match(tabsFile, /if \(value === "paper" && allowPaper\) return "paper";/);
  assert.match(tabsFile, /return "positions";/);
  assert.match(app, /Navigate to="\/reports\?tab=orders"/);
  assert.match(app, /Navigate to="\/reports\?tab=positions"/);
  assert.match(side, /label: "Position & Orders"/);
  assert.doesNotMatch(side, /to: "\/orders"/);
  const tabs = hub.split("desk-tabs")[1] || "";
  const position = tabs.indexOf("Position");
  const orders = tabs.indexOf("Orders");
  const reports = tabs.lastIndexOf("Reports");
  assert.ok(position >= 0 && orders > position && reports > orders);
  const reportsPage = fs.readFileSync(path.join(root, "src/pages/Reports.tsx"), "utf8");
  const ordersPage = fs.readFileSync(path.join(root, "src/pages/Orders.tsx"), "utf8");
  const book = fs.readFileSync(path.join(root, "src/pages/MemberBook.tsx"), "utf8");
  assert.match(reportsPage, /data-profit-people="true"/);
  assert.match(reportsPage, />Name</);
  assert.match(reportsPage, />Email</);
  assert.match(reportsPage, />Mobile</);
  assert.match(reportsPage, />Broker</);
  assert.match(reportsPage, />Position</);
  assert.match(ordersPage, /Reason: \{displayOrderReason/);
  assert.match(ordersPage, /book === "paper"/);
  assert.match(ordersPage, /isLiveBrokerTrade/);
  assert.match(book, /Reason: \{displayOrderReason/);
  assert.match(book, /ProfitOwnerCard/);
  assert.match(book, /data-paper-tab="true"/);
  assert.match(book, /data-member-book="paper"/);
  assert.match(hub, /data-paper-tab="true"/);
  assert.match(hub, /book="live"/);
  assert.match(hub, /PaperTrading/);
  const paperPage = fs.readFileSync(path.join(root, "src/pages/PaperTrading.tsx"), "utf8");
  assert.match(paperPage, /data-paper-book="true"/);
  assert.match(paperPage, /book="paper"/);
  const liveBook = fs.readFileSync(path.join(root, "src/components/desk/MemberLiveBook.tsx"), "utf8");
  assert.match(liveBook, /Reason: \{displayOrderReason/);
});

test("User Algos page keeps enroll and broker, not Daily P&L or broker books", () => {
  const plans = fs.readFileSync(path.join(root, "src/pages/MemberPlans.tsx"), "utf8");
  const mobile = fs.readFileSync(path.join(root, "mobile/src/screens/MemberPlansScreen.tsx"), "utf8");
  assert.match(plans, /Algo Strategies/);
  assert.match(plans, /Subscriptions/);
  assert.match(plans, /Broker selection/);
  assert.doesNotMatch(plans, /MemberLiveBook/);
  assert.doesNotMatch(plans, /Daily P&L/);
  assert.doesNotMatch(plans, /Order book/);
  assert.doesNotMatch(plans, /Order history/);
  assert.doesNotMatch(plans, /Trade book/);
  assert.doesNotMatch(plans, /Open positions/);
  assert.doesNotMatch(mobile, /desk\?\.positions/);
});
