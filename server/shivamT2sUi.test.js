import assert from "node:assert/strict";
import fs from "node:fs";
import path from "path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

test("Shivam T2S card, builder, APIs, and reports are wired", () => {
  const builder = fs.readFileSync(path.join(root, "src/components/dashboard/StrategyBuilder.tsx"), "utf8");
  const page = fs.readFileSync(path.join(root, "src/pages/Algo.tsx"), "utf8");
  const reports = fs.readFileSync(path.join(root, "src/pages/Reports.tsx"), "utf8");
  const api = fs.readFileSync(path.join(root, "server/index.js"), "utf8");
  const lib = fs.readFileSync(path.join(root, "src/lib/strategies.ts"), "utf8");
  const css = fs.readFileSync(path.join(root, "src/index.css"), "utf8");
  const strategies = fs.readFileSync(path.join(root, "server/strategies.js"), "utf8");
  assert.match(lib, /"shivam-t2s"/);
  assert.match(lib, /SHIVAM_T2S_NAME = "Shivam T2S Strategy"/);
  assert.match(builder, /title="SHIVAM T2S"/);
  assert.match(builder, /data-shivam-capital="true"/);
  assert.match(builder, /Capital management/);
  assert.match(page, /data-shivam-capital="true"/);
  assert.doesNotMatch(page, /1–100 filled BUY entries today/);
  assert.doesNotMatch(page, /Re-entries count\. Rejected orders do not/);
  assert.doesNotMatch(builder, /Filled BUY entries today count toward the limit/);
  assert.match(builder, /data-mir-trade-mode="true"/);
  assert.match(builder, /emptyStrategy\(testDesk \? "shivam-t2s"/);
  assert.match(builder, /data-shivam-settings="true"/);
  assert.match(builder, /data-shivam-timeframes="true"/);
  assert.match(builder, /data-shivam-settings="true"[\s\S]*data-shivam-timeframes="true"/);
  assert.match(builder, /function DeskTimeframeSelect/);
  assert.match(builder, /mark="shivam-index"/);
  assert.match(builder, /mark="shivam-ce"/);
  assert.match(builder, /mark="shivam-pe"/);
  assert.match(builder, /label="Index timeframe"/);
  assert.match(builder, /label="CE timeframe"/);
  assert.match(builder, /label="PE timeframe"/);
  assert.match(builder, /<option value="custom">Custom<\/option>/);
  assert.match(builder, /Minutes 1–60/);
  assert.doesNotMatch(builder, /mark="shivam-index"[\s\S]{0,200}<FirstCandleTimeframeBar/);
  assert.doesNotMatch(builder, /Index · 5m 15m 30m 1hr Custom 1–60/);
  assert.match(builder, /shivam \? null : hedge \?/);
  assert.match(builder, /data-shivam-name-broker="true"/);
  assert.match(builder, /data-shivam-broker="true"/);
  assert.match(builder, /data-shivam-daily-limit="true"/);
  assert.match(
    builder,
    /data-shivam-capital="true"[\s\S]*data-shivam-name-broker="true"[\s\S]*Strategy name[\s\S]*data-shivam-broker="true"[\s\S]*data-shivam-daily-limit="true"[\s\S]*data-shivam-settings="true"/,
  );
  assert.doesNotMatch(builder, /data-shivam-settings="true"[\s\S]*data-shivam-name-broker="true"/);
  assert.match(builder, /\{shivam \? null : \(\s*<label className="mt-2.5 block text-xs font-semibold text-slate-500" data-trade-limit="daily"/);
  assert.doesNotMatch(page, /function ShivamCardTimeframes/);
  assert.doesNotMatch(page, /data-shivam-timeframes/);
  assert.doesNotMatch(page, /mark="shivam-index"/);
  assert.match(page, /data-shivam-tf="true"/);
  assert.match(page, /IDX \{deskTfLabel\(algo\.indexTimeframe \|\| algo\.timeframe\)\}/);
  assert.match(lib, /SHIVAM_T2S_TIMEFRAMES = DESK_TIMEFRAME_PRESETS/);
  assert.doesNotMatch(builder, /Authorize live after paper trading/);
  assert.match(page, /data-shivam-signal/);
  assert.match(page, /NO Trade/);
  assert.match(page, /● ● ●/);
  assert.match(page, /data-shivam-details/);
  assert.match(page, /export function AlgoTest/);
  assert.match(page, /data-algo-test-tab/);
  assert.match(page, /navigate\("\/algo-test"\)/);
  assert.match(page, /\["shivam-t2s", "SHIVAM T2S"\]/);
  assert.match(page, /isolated && !shivam/);
  assert.match(page, /data-start-live="true"/);
  assert.match(page, /data-shivam-map="true"/);
  assert.match(page, /Latest activity/);
  assert.match(page, /data-latest-activity="true"/);
  assert.match(page, /data-shivam-activity="true"/);
  assert.match(page, /data-shivam-activity-text="true"/);
  assert.match(page, /function shivamActivityText/);
  assert.match(page, /<ShivamCapitalStrip algo=\{algo\} \/> : null\}[\s\S]{0,240}data-shivam-activity="true"/);
  assert.match(page, /shivamActivityText\(algo, orders\)/);
  assert.match(css, /\.blotter-card\[data-shivam-strategy="true"\][\s\S]{0,80}overflow:\s*visible/);
  assert.match(page, /data-test-broker-order="true"/);
  assert.match(page, /Mapped clients copy 1 lot on their own broker/);
  assert.doesNotMatch(page, /Mapped clients will not copy/);
  assert.doesNotMatch(page, /Mapped clients were not copied/);
  assert.match(page, /data-shivam-live-check/);
  assert.match(page, /algo.enabled && algo.runMode === "live"/);
  assert.doesNotMatch(page, /algo.enabled \|\| algo.status === "LIVE"/);
  assert.match(api, /\/api\/algos\/:id\/test-order/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/live-status/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/test-order/);
  assert.match(builder, /liveAuthorized: true/);
  assert.match(builder, /testDesk && !shivam/);
  assert.match(strategies, /id: SHIVAM_T2S_SEED_ID/);
  assert.match(strategies, /ALWAYS_ON_FIRST_CANDLE_IDS, SHIVAM_T2S_SEED_ID/);
  assert.doesNotMatch(reports, /data-shivam-report/);
  assert.doesNotMatch(reports, /downloadShivamT2sReport/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/config/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/reports\/pdf/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/reports\/excel/);
});
