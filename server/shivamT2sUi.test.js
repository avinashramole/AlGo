import assert from "node:assert/strict";
import fs from "node:fs";
import path from "path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

test("Shivam T2S card, builder, APIs, and reports are wired", () => {
  const builder = fs.readFileSync(path.join(root, "src/components/dashboard/StrategyBuilder.tsx"), "utf8");
  const page = fs.readFileSync(path.join(root, "src/pages/Algo.tsx"), "utf8");
  const reports = fs.readFileSync(path.join(root, "src/pages/Reports.tsx"), "utf8");
  const api = fs.readFileSync(path.join(root, "server/index.js"), "utf8");
  const lib = fs.readFileSync(path.join(root, "src/lib/strategies.ts"), "utf8");
  const strategies = fs.readFileSync(path.join(root, "server/strategies.js"), "utf8");
  assert.match(lib, /"shivam-t2s"/);
  assert.match(lib, /SHIVAM_T2S_NAME = "Shivam T2S Strategy"/);
  assert.match(builder, /title="SHIVAM T2S"/);
  assert.match(builder, /data-shivam-capital="true"/);
  assert.match(builder, /Capital management/);
  assert.match(page, /data-shivam-capital="true"/);
  assert.doesNotMatch(page, /1–100 filled BUY entries today/);
  assert.doesNotMatch(page, /Re-entries count\. Rejected orders do not/);
  assert.doesNotMatch(builder, /Filled BUY entries today count toward the limit/);
  assert.match(builder, /data-mir-trade-mode="true"/);
  assert.match(builder, /emptyStrategy\(testDesk \? "shivam-t2s"/);
  assert.match(builder, /data-shivam-settings="true"/);
  assert.doesNotMatch(builder, /Authorize live after paper trading/);
  assert.match(page, /data-shivam-signal/);
  assert.match(page, /NO Trade/);
  assert.match(page, /● ● ●/);
  assert.match(page, /data-shivam-details/);
  assert.match(page, /export function AlgoTest/);
  assert.match(page, /data-algo-test-tab/);
  assert.match(page, /navigate\("\/algo-test"\)/);
  assert.match(page, /\["shivam-t2s", "SHIVAM T2S"\]/);
  assert.match(page, /isolated && !shivam/);
  assert.match(page, /data-start-live="true"/);
  assert.match(page, /data-shivam-map="true"/);
  assert.match(page, /data-test-broker-order="true"/);
  assert.match(page, /data-shivam-live-check/);
  assert.match(page, /algo.enabled && algo.runMode === "live"/);
  assert.doesNotMatch(page, /algo.enabled \|\| algo.status === "LIVE"/);
  assert.match(api, /\/api\/algos\/:id\/test-order/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/live-status/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/test-order/);
  assert.match(builder, /liveAuthorized: true/);
  assert.match(builder, /testDesk && !shivam/);
  assert.match(strategies, /id: SHIVAM_T2S_SEED_ID/);
  assert.match(strategies, /ALWAYS_ON_FIRST_CANDLE_IDS, SHIVAM_T2S_SEED_ID/);
  assert.doesNotMatch(reports, /data-shivam-report/);
  assert.doesNotMatch(reports, /downloadShivamT2sReport/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/config/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/reports\/pdf/);
  assert.match(api, /\/api\/strategies\/shivam-t2s\/reports\/excel/);
});
