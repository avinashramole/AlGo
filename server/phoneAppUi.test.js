import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

test("Phone app uses Trade2Smart home, tabs, and member book", () => {
  const home = fs.readFileSync(path.join(root, "src/components/home/HomeOverview.tsx"), "utf8");
  const adminHome = fs.readFileSync(path.join(root, "src/pages/Dashboard.tsx"), "utf8");
  const userHome = fs.readFileSync(path.join(root, "src/pages/UserHome.tsx"), "utf8");
  const nav = fs.readFileSync(path.join(root, "src/components/layout/MobileNav.tsx"), "utf8");
  const login = fs.readFileSync(path.join(root, "src/pages/Login.tsx"), "utf8");
  const book = fs.readFileSync(path.join(root, "src/pages/MemberBook.tsx"), "utf8");
  const mobileProfile = fs.readFileSync(path.join(root, "mobile/src/screens/ProfileScreen.tsx"), "utf8");
  assert.match(mobileProfile, /Broker name/);
  assert.match(mobileProfile, /label="Broker name"/);
  assert.doesNotMatch(mobileProfile, /label="Name"/);
  assert.doesNotMatch(mobileProfile, /label="Email"/);
  assert.doesNotMatch(mobileProfile, /label="Mobile no"/);
  assert.doesNotMatch(mobileProfile, /label="Role"/);
  const app = fs.readFileSync(path.join(root, "src/App.tsx"), "utf8");

  assert.match(home, /data-home-overview="phone"/);
  assert.match(home, /Hello,/);
  assert.match(home, /\{tape\}/);
  assert.match(home, /data-home-shortcuts="algos-positions-orders"/);
  assert.doesNotMatch(home, /Active Strategies/);
  assert.doesNotMatch(home, /Position and Orders/);
  assert.match(home, /label="Algos"/);
  assert.match(home, /label="Position"/);
  assert.match(home, /label="Orders"/);
  const algos = home.indexOf('label="Algos"');
  const position = home.indexOf('label="Position"');
  const orders = home.indexOf('label="Orders"');
  assert.ok(algos >= 0 && algos < position && position < orders);
  assert.doesNotMatch(home, /Waiting for the next quote/);
  assert.doesNotMatch(home, /quote\?\.symbol/);
  assert.match(adminHome, /tape=\{<TickerStrip/);
  const memberHome = fs.readFileSync(path.join(root, "src/components/home/UserHomeBoard.tsx"), "utf8");
  assert.match(memberHome, /data-home-overview="member"/);
  assert.match(memberHome, /greetingIst\(\)/);
  const formatSrc = fs.readFileSync(path.join(root, "src/lib/format.ts"), "utf8");
  assert.match(formatSrc, /return "Good Morning"/);
  assert.match(formatSrc, /return "Good Afternoon"/);
  assert.match(formatSrc, /return "Good Evening"/);
  assert.doesNotMatch(formatSrc, /Good evening/);
  assert.match(memberHome, /Trade2Smart\. Stay Disciplined/);
  assert.match(memberHome, /Portfolio Overview/);
  assert.match(memberHome, /Capital Utilization/);
  assert.match(memberHome, /data-capital-use="true"/);
  assert.match(memberHome, /data-capital-bar="used-free"/);
  assert.match(memberHome, /bg-down/);
  assert.match(memberHome, /bg-up/);
  assert.match(memberHome, /% used/);
  assert.match(memberHome, /Your Subscription Plan/);
  assert.match(memberHome, /Trading Workspace/);
  assert.match(memberHome, /Algorithmic Strategies/);
  assert.match(memberHome, /Market tape/);
  assert.match(memberHome, /data-home-workspace="algos-tape"/);
  assert.match(memberHome, /to="\/tape"/);
  assert.doesNotMatch(memberHome, /getElementById\("market-tape"\)/);
  assert.doesNotMatch(memberHome, /href="#market-tape"/);
  assert.doesNotMatch(memberHome, /id="market-tape"/);
  assert.match(userHome, /UserHomeBoard/);
  assert.doesNotMatch(userHome, /MemberIndexBoard/);
  assert.doesNotMatch(userHome, /getMemberQuotes/);
  const tapePage = fs.readFileSync(path.join(root, "src/pages/MemberTape.tsx"), "utf8");
  assert.match(tapePage, /data-member-tape-page="true"/);
  assert.match(tapePage, /MemberIndexBoard/);
  assert.doesNotMatch(userHome, /Kotak account after the trade login/);
  assert.doesNotMatch(userHome, /Neo sid and today's session token/);
  assert.match(userHome, /data-user-home="true"/);
  const css = fs.readFileSync(path.join(root, "src/index.css"), "utf8");
  const shell = fs.readFileSync(path.join(root, "src/components/layout/AppShell.tsx"), "utf8");
  const roles = fs.readFileSync(path.join(root, "src/lib/roles.ts"), "utf8");
  assert.match(roles, /t2s-user-desk/);
  assert.match(roles, /export function markUserDeskDocument/);
  assert.match(shell, /markUserDeskDocument/);
  assert.match(shell, /data-user-desk=\{userDesk \? "true" : undefined\}/);
  assert.match(css, /html\.t2s-user-desk:not\(\.dark\)/);
  assert.match(css, /html\.t2s-user-desk:not\(\.dark\)[\s\S]*--bg: #ffffff/);
  assert.match(css, /html\.t2s-user-desk:not\(\.dark\)[\s\S]*\[data-user-desk\]/);
  assert.doesNotMatch(userHome, /showShortcuts/);
  assert.doesNotMatch(userHome, /CopyAlerts/);
  assert.doesNotMatch(userHome, /Copied BUY/);
  assert.doesNotMatch(userHome, /desk\?\.alerts/);
  assert.doesNotMatch(userHome, /hidden md:block/);
  assert.doesNotMatch(adminHome, /quote=/);
  assert.doesNotMatch(userHome, /quote=/);
  assert.match(nav, /label: "Algos"/);
  assert.match(nav, /label: "Position & Orders", icon: FileText, admin: true/);
  assert.match(nav, /label: "Profile", icon: User, admin: true/);
  assert.match(nav, /data-apk-nav="member"/);
  assert.match(nav, /label: "Position"/);
  assert.match(nav, /label: "Orders"/);
  assert.match(nav, /label: "Broker"/);
  assert.match(nav, /data-apk-logout="true"/);
  assert.match(nav, /to: "\/positions"/);
  assert.match(nav, /to: "\/orders"/);
  assert.match(nav, /to: "\/broker"/);
  assert.match(book, /data-member-report-download="pdf"/);
  assert.match(book, /downloadMemberReport/);
  const sidebar = fs.readFileSync(path.join(root, "src/components/layout/Sidebar.tsx"), "utf8");
  const header = fs.readFileSync(path.join(root, "src/components/layout/Header.tsx"), "utf8");
  assert.match(sidebar, /label: "Profile", icon: User, admin: true/);
  assert.match(sidebar, /to: "\/settings", label: "Settings", icon: Settings \}/);
  assert.match(sidebar, /label: "Support", icon: Headphones, member: true/);
  assert.match(sidebar, /label: "Password", icon: KeyRound, member: true/);
  assert.doesNotMatch(sidebar, /label: "Alerts"/);
  assert.match(header, /data-profile-shortcut="true"/);
  assert.match(header, /to="\/profile"/);
  assert.doesNotMatch(header, /data-settings-shortcut/);
  assert.doesNotMatch(header, />Settings</);
  assert.match(header, />Profile</);
  assert.doesNotMatch(memberHome, /data-profile-home/);
  assert.match(roles, /to: "\/settings", label: "Settings"/);
  assert.match(roles, /to: "\/support", label: "Support"/);
  const userNavBlock = roles.slice(roles.indexOf("export const userNav"), roles.indexOf("export function navForUser"));
  assert.doesNotMatch(userNavBlock, /Alerts/);
  assert.match(userNavBlock, /Password/);
  assert.match(userNavBlock, /Position[\s\S]*Orders[\s\S]*Support[\s\S]*Password[\s\S]*Settings/);
  assert.doesNotMatch(userNavBlock, /Position & Orders/);
  const sidebarNav = sidebar.slice(sidebar.indexOf("const items"), sidebar.indexOf("export function Sidebar"));
  assert.match(sidebarNav, /label: "Password"[\s\S]*to: "\/settings", label: "Settings"/);
  const loginPassword = fs.readFileSync(path.join(root, "src/components/desk/LoginPasswordCard.tsx"), "utf8");
  assert.match(loginPassword, /id="login-password"/);
  assert.match(loginPassword, /location\.hash !== "#login-password"/);
  assert.match(loginPassword, /scrollIntoView/);
  assert.match(login, /t2s-auth-tabs/);
  assert.match(login, /Login with Google/);
  assert.match(book, /data-member-book="orders"/);
  assert.match(book, /data-member-positions-page="true"/);
  assert.match(book, /data-member-orders-page="true"/);
  assert.match(book, /data-member-report-download="pdf"/);
  assert.doesNotMatch(book, /Position & Orders/);
  assert.match(app, /MemberReports/);
  assert.match(app, /MemberPositions/);
  assert.match(app, /MemberOrders/);
  assert.match(app, /RoleReports/);
  assert.match(app, /RolePositions/);
  assert.match(app, /RoleOrders/);
  assert.match(app, /MemberTape/);
  assert.match(app, /MemberBroker/);
  assert.match(app, /path="tape"/);
  assert.match(app, /path="broker"/);
  assert.match(app, /Navigate to="\/reports\?tab=orders"/);
});
