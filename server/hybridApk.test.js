test("login page has a real Android APK download link", () => {
  const login = fs.readFileSync(path.join(root, "src/pages/Login.tsx"), "utf8");
  const nginx = fs.readFileSync(path.join(root, "deploy/nginx-trade2smart.conf"), "utf8");
  const index = fs.readFileSync(path.join(root, "server/index.js"), "utf8");
  const apk = path.join(root, "releases/Trade2Smart-web.apk");
  assert.match(login, /function downloadAndroidApk/);
  assert.match(login, /data-android-apk="download"/);
  assert.match(login, /onClick=\{downloadAndroidApk\}/);
  assert.match(login, /href = "\/Trade2Smart-web\.apk"/);
  assert.match(login, /function installIosApp/);
  assert.doesNotMatch(login, /setHint\("iPhone: open this site in Safari/);
  assert.match(
    login,
    /function downloadAndroidApk\(\) \{\n(?:  .+\n)+  link\.remove\(\);\n\}\n\nexport function Login\(\)/,
  );
  assert.doesNotMatch(login, /<a className="t2s-apk-download" href="\/Trade2Smart-web\.apk"/);
  assert.match(index, /sendAndroidApk/);
  assert.match(nginx, /Trade2Smart-web\.apk/);
  assert.equal(fs.existsSync(apk), true);
  assert.ok(fs.statSync(apk).size > 1000);
  const appJson = fs.readFileSync(path.join(root, "mobile/app.json"), "utf8");
  const renderIcons = fs.readFileSync(path.join(root, "scripts/render-brand-icons.py"), "utf8");
  const syncIcons = fs.readFileSync(path.join(root, "scripts/sync-brand-icons.py"), "utf8");
  assert.match(appJson, /"icon": "\.\/assets\/icon\.png"/);
  assert.match(renderIcons, /app-icon-source\.png/);
  assert.match(syncIcons, /app-icon-source\.png/);
  assert.match(syncIcons, /AppIcon-512@2x\.png/);
  assert.match(syncIcons, /LAUNCHER_PAD = 0\.0/);
  assert.match(syncIcons, /ADAPTIVE_PAD = 0\.12/);
  assert.match(renderIcons, /pwa-512\.png/);
  assert.match(renderIcons, /pad=0\.12/);
  assert.match(renderIcons, /Keep the official app icon plate/);
  assert.doesNotMatch(renderIcons, /src = knock_white\(load_source\(\)\)/);
  assert.equal(fs.existsSync(path.join(root, "mobile/assets/app-icon-source.png")), true);
  assert.equal(fs.existsSync(path.join(root, "mobile/assets/icon.png")), true);
  assert.equal(fs.existsSync(path.join(root, "public/pwa-512.png")), true);
  assert.equal(fs.existsSync(path.join(root, "public/apple-touch-icon.png")), true);
  assert.equal(
    fs.existsSync(path.join(root, "android/app/src/main/res/mipmap-xxxhdpi/ic_launcher.png")),
    true,
  );
  assert.equal(
    fs.existsSync(path.join(root, "android/app/src/main/res/mipmap-xxxhdpi/ic_launcher_foreground.png")),
    true,
  );
  const webManifest = fs.readFileSync(path.join(root, "public/manifest.webmanifest"), "utf8");
  assert.match(webManifest, /pwa-512\.png/);
  assert.match(webManifest, /standalone/);
  const indexHtml = fs.readFileSync(path.join(root, "index.html"), "utf8");
  assert.match(indexHtml, /apple-touch-startup-image/);
  assert.match(indexHtml, /apple-mobile-web-app-capable/);
});
